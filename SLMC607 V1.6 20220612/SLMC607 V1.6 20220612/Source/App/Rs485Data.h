/**
 * @file    Rs485Data.h
 * @brief   RS485通信协议定义
 * @details 定义RS485通信协议常量和远程控制命令
 *          支持MOS开关控制和告警清除
 */

#ifndef __RS485DATA_H
#define __RS485DATA_H
#include "sys.h"

/* ==================== 通信控制常量 ==================== */
#define OPER_ON   1    // 操作使能
#define OPER_OFF  0    // 操作禁用

/* ==================== 全局变量声明 ==================== */
extern u8 Bq769xx_Oper_EN;    // BQ769xx操作使能标志
extern u8 Bq769xx_Oper_Type;  // BQ769xx操作类型

/* ==================== 远程控制命令枚举定义 ==================== */
/**
 * @brief RS485远程控制命令类型
 * @details 定义通过RS485可发送的远程控制命令
 */
typedef enum
{
	COMM_MIN = 0,            // 最小命令值
	COMM_DSG_ON = 1,         // 开启放电MOS
	COMM_DSG_OFF = 2,        // 关闭放电MOS
	COMM_CHG_ON = 3,          // 开启充电MOS
	COMM_CHG_OFF = 4,         // 关闭充电MOS
	COMM_CLEAR_ALERT = 5,    // 清除告警
	COMM_ENTER_SHIP = 6,      // 进入关机模式
	COMM_MAX = 7,             // 最大命令值
} eCOMM_TYPE;

/* ==================== 函数声明 ==================== */
void Rs485_Send_Test(void);                          // RS485发送测试
u16 Rs485_Read_Data(u8* resp_buf, u8 recvsize);  // RS485数据读取

#endif  // __RS485DATA_H
